const LANG_META = {
  sq: { code: "SQ" },
  en: { code: "EN" },
  fr: { code: "FR" },
  de: { code: "DE" },
};

function applyLanguage(lang) {
  const dict = I18N[lang] || I18N.sq;
  document.documentElement.lang = lang;
  document.body.dataset.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] != null) el.textContent = dict[key];
  });

  const meta = LANG_META[lang];
  const codeEl = document.getElementById("langPillCode");
  if (codeEl && meta) codeEl.textContent = meta.code;

  const radio = document.querySelector(`input[name="lang"][value="${lang}"]`);
  if (radio) radio.checked = true;

  localStorage.setItem("gjeodeti-lang", lang);
}
